/**
 * Production build for dsh-plugin-updates.
 *
 * Two independent bundles, both plain ESM:
 *  - dist/index.js   host half, runs inside the DSH profile process (Node)
 *  - dist/client.js  client half, loaded by the DSH module loader in the browser
 *
 * The client bundle must keep `require('react')` as a runtime call: the loader
 * injects its own `require` into the factory, and React is provided by the host
 * page, never bundled here.
 *
 * The package version is injected as `__PU_VERSION__` so there is exactly one
 * place to bump it (package.json). Both halves print it in their diagnostics and
 * the toolbar badge, which is how a user tells whether a reload actually loaded
 * the new code.
 */
import { rm, mkdir, readFile } from 'node:fs/promises';
import { build } from 'esbuild';

const pkg = JSON.parse(await readFile(new URL('./package.json', import.meta.url), 'utf8'));
if (typeof pkg.version !== 'string' || pkg.version === '') {
  throw new Error('package.json has no version');
}

const shared = {
  bundle: true,
  minify: true,
  legalComments: 'none',
  target: 'es2022',
  logLevel: 'info',
  define: {
    __PU_VERSION__: JSON.stringify(pkg.version),
  },
};

await rm('dist', { recursive: true, force: true });
await mkdir('dist', { recursive: true });

await build({
  ...shared,
  entryPoints: ['src/host/index.ts'],
  outfile: 'dist/index.js',
  platform: 'node',
  format: 'esm',
  packages: 'external',
  banner: { js: `// dsh-plugin-updates@${pkg.version} host half — generated by \`npm run build\`; see src/host/index.ts` },
});

await build({
  ...shared,
  entryPoints: ['src/client/index.ts'],
  outfile: 'dist/client.js',
  platform: 'browser',
  format: 'esm',
  banner: { js: `// dsh-plugin-updates@${pkg.version} client half — generated by \`npm run build\`; see src/client/index.ts` },
});

console.log(`built dsh-plugin-updates@${pkg.version}`);
